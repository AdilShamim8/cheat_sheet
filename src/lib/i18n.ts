export const DICTS: Record<LanguageCode, Dict> = { en, zh, es, ar, fr, de, hi, bn, ja };

/** Translate a key in the current language, with {placeholder} substitution. */
export function t(lang: LanguageCode, key: string, params?: Record<string, string | number>): string {
  const dict = DICTS[lang] ?? en;
  let s = dict[key] ?? en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return s;
}
